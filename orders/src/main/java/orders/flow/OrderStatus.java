package orders.flow;

/**
 * Статусы заказа.
 *
 * === ВОЗМОЖНЫЕ СТАТУСЫ ===
 *
 * PENDING  — заказ создан, оплата ещё не завершена (асинхронный путь)
 * PAID     — платёж прошёл, резерв товара остаётся
 * REJECTED — платёж отклонён, резерв снят
 *
 * === ОТКРЫТЫЙ ВОПРОС (S2) ===
 *
 * Что делать с заказом, по которому исчерпаны все повторы оплаты:
 * оставить PENDING (текущее поведение: его подберёт Reaper) или
 * переводить в REJECTED — зависит от требований.
 */
public enum OrderStatus {
    PENDING,
    PAID,
    REJECTED
}
