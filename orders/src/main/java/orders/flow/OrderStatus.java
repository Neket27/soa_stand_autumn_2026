package orders.flow;

/**
 * Статусы заказа.
 *
 * === ВОЗМОЖНЫЕ СТАТУСЫ ===
 *
 * PENDING  — заказ создан, оплата ещё не завершена
 * PAID     — заказ оплачен успешно
 * REJECTED — заказ отклонён (банк отклонил или ошибка)
 *
 * === ЧТО СДЕЛАТЬ САМОМУ (S1-S2) ===
 *
 * S1: Заказ должен быть либо PAID, либо REJECTED.
 *     — PAID: платёж прошёл, резерв товара остаётся
 *     — REJECTED: платёж отклонён, резерв товара снят
 *
 * S2: Заказ может быть PENDING, пока Consumer повторяет попытку.
 *     — Если все попытки исчерпаны — заказ должен стать REJECTED
 *       или остаться PENDING (зависит от требований)
 */
public enum OrderStatus {
    PENDING,
    PAID,
    REJECTED
}
